/* Resolve the house-LUT data dir in both layouts:
   - esbuild bundle:   <artifact>/dist/index.mjs      -> <artifact>/data/luts
   - ts source (tests): <artifact>/src/routes/lut.ts -> <artifact>/data/luts */
function resolveLutsDir(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  const candidates = [
    join(here, "..", "data", "luts"),
    join(here, "..", "..", "data", "luts"),
  ];
  for (const c of candidates) {
    if (existsSync(join(c, "presets.json"))) return c;
  }
  return candidates[0];
}
