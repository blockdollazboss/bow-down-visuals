/**
 * POST /api/lut/validate — validate an uploaded LUT without spending.
 * multipart: lut (file). Free.
 */
router.post("/lut/validate", requireAuth, upload.single("lut"), (req, res) => {
  try {
    if (!req.file) {
      res.status(400).json({ error: "Upload a .cube or .3dl file in the 'lut' field." });
      return;
    }
    const parsed = validateLutBuffer(req.file.buffer, req.file.originalname);
    res.json({
      valid: true,
      format: parsed.format,
      title: parsed.title,
      size: parsed.size,
    });
  } catch (err) {
    if (err instanceof LutValidationError) {
      res.status(400).json({ valid: false, error: err.message });
      return;
    }
    throw err;
  }
});

/**
 * POST /api/lut/preview — free thumbnail preview of the LUT on a video frame.
 * multipart: video (file) | videoUrl (field); lut (file) | presetId | lutId (fields).
 * Returns a JPEG of the middle frame with the LUT applied.
 */
router.post(
  "/lut/preview",
  requireAuth,
  upload.fields([
    { name: "video", maxCount: 1 },
    { name: "lut", maxCount: 1 },
  ]),
  async (req, res) => {
    const workDir = await mkdtemp(join(tmpdir(), "lutpreview-"));
    try {
      const inputPath = await fetchVideo(req, workDir, (req.body ?? {}) as Record<string, unknown>);
      const { cubePath } = await resolveLut(req, workDir);

      // Seek to the middle of the clip for a representative frame.
      let seekSec = 1;
      try {
        const { stdout } = await execFileAsync(
          "ffprobe",
          ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", inputPath],
          { timeout: 30_000 },
        );
        const dur = parseFloat((stdout ?? "").trim());
        if (Number.isFinite(dur) && dur > 0) seekSec = Math.max(0.2, dur / 2);
      } catch { /* fall back to 1s */ }

      const outPath = join(workDir, "preview.jpg");
      await execFileAsync(
        "ffmpeg",
        [
          "-y",
          "-ss", String(seekSec),
          "-i", inputPath,
          "-vframes", "1",
          "-vf", `lut3d=file='${cubePath}',scale=640:-2`,
          "-q:v", "4",
          outPath,
        ],
        { timeout: 120_000 },
      );
      res.type("image/jpeg").send(await readFile(outPath));
    } catch (err) {
      sendLutError(res, err, req, "[lut] preview failed");
    } finally {
      await rm(workDir, { recursive: true, force: true }).catch(() => {});
    }
  },
);

/**
 * POST /api/apply-lut — burn a LUT into a clip via ffmpeg lut3d.
 * multipart: video (file) | videoUrl (field); lut (file) | presetId | lutId (fields).
 * 150 Visual Bucs. Auto-refund on failure.
 */
router.post(
  "/apply-lut",
  requireAuth,
  upload.fields([
    { name: "video", maxCount: 1 },
    { name: "lut", maxCount: 1 },
  ]),
  async (req, res) => {
    const currentCredits = req.userCredits ?? 0;
    if (currentCredits < LUT_APPLY_COST) {
      res.status(402).json({
        error: "out_of_credits",
        message: `Not enough Visual Bucs — this costs ${LUT_APPLY_COST.toLocaleString("en-US")} Visual Bucs.`,
        required: LUT_APPLY_COST,
        balance: currentCredits,
      });
      return;
    }

    const workDir = await mkdtemp(join(tmpdir(), "lutapply-"));
    let charged = false;
    let displayName = "LUT";
    try {
      const inputPath = await fetchVideo(req, workDir, (req.body ?? {}) as Record<string, unknown>);
      const resolved = await resolveLut(req, workDir);
      displayName = resolved.displayName;

      let creditsAfter: number;
      try {
        creditsAfter = await chargeCredits(req.userId!, LUT_APPLY_COST, {
          action: `LUT apply (${displayName})`,
        });
        charged = true;
      } catch (err) {
        if (err instanceof OutOfCreditsError) {
          res.status(402).json({ error: "out_of_credits", message: "Not enough Visual Bucs." });
          return;
        }
        throw err;
      }

      const outputPath = join(workDir, "output.mp4");
      await execFileAsync(
        "ffmpeg",
        [
          "-y",
          "-i", inputPath,
          "-vf", `lut3d=file='${resolved.cubePath}'`,
          "-c:v", "libx264",
          "-preset", "fast",
          "-crf", "18",
          "-pix_fmt", "yuv420p",
          "-c:a", "copy",
          outputPath,
        ],
        { timeout: 600_000 },
      );

      const buffer = await readFile(outputPath);
      const objectName = `lutgrade/${req.userId}/${randomUUID()}.mp4`;
      const storageRef = await uploadMediaToSupabaseStorage(objectName, buffer, "video/mp4");
      const url = await refreshSupabaseStorageUrl(storageRef);

      res.json({ url, storageRef, lut: displayName, creditsRemaining: creditsAfter });
    } catch (err) {
      if (charged) {
        await refundCredits(req.userId!, LUT_APPLY_COST, {
          action: "LUT apply — Refund",
        }).catch(() => {});
      }
      sendLutError(res, err, req, "[lut] apply failed");
    } finally {
      await rm(workDir, { recursive: true, force: true }).catch(() => {});
    }
  },
);

/**
 * POST /api/lut/upload — save a validated LUT to "My LUTs" for reuse.
 * multipart: lut (file); optional field: name. Free.
 */
router.post("/lut/upload", requireAuth, upload.single("lut"), async (req, res) => {
  try {
    if (!req.file) {
      res.status(400).json({ error: "Upload a .cube or .3dl file in the 'lut' field." });
      return;
    }
    const parsed = validateLutBuffer(req.file.buffer, req.file.originalname);
    const name =
      (typeof req.body?.name === "string" && req.body.name.trim().slice(0, 80)) ||
      parsed.title ||
      req.file.originalname.replace(/\.[^.]+$/, "");
    const ext = parsed.format === "3dl" ? "3dl" : "cube";
    const objectName = `luts/${req.userId}/${randomUUID()}.${ext}`;
    const storageRef = await uploadMediaToSupabaseStorage(
      objectName,
      Buffer.from(parsed.cubeText, "utf8"),
      "text/plain",
    );
    const [row] = await db
      .insert(userLutsTable)
      .values({
        user_id: req.userId!,
        name,
        format: parsed.format,
        lut_size: parsed.size,
        storage_ref: storageRef,
      })
      .returning();
    const url = await refreshSupabaseStorageUrl(storageRef).catch(() => null);
    res.json({
      id: row!.id,
      name: row!.name,
      format: row!.format,
      size: row!.lut_size,
      url,
      createdAt: row!.created_at,
    });
  } catch (err) {
    sendLutError(res, err, req, "[lut] upload failed");
  }
});

/** GET /api/lut/my — list the user's saved LUTs. Free. */
router.get("/lut/my", requireAuth, async (req, res) => {
  try {
    const rows = await db
      .select()
      .from(userLutsTable)
      .where(eq(userLutsTable.user_id, req.userId!))
      .orderBy(desc(userLutsTable.created_at));
    const items = await Promise.all(
      rows.map(async (r) => ({
        id: r.id,
        name: r.name,
        format: r.format,
        size: r.lut_size,
        url: await refreshSupabaseStorageUrl(r.storage_ref).catch(() => null),
        createdAt: r.created_at,
      })),
    );
    res.json({ luts: items });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Failed to load saved LUTs.";
    req.log.error({ err: message }, "[lut] my-list failed");
    res.status(500).json({ error: message });
  }
});

/** DELETE /api/lut/my/:id — delete a saved LUT. Free. */
router.delete("/lut/my/:id", requireAuth, async (req, res) => {
  try {
    const id = String(req.params.id ?? "");
    const deleted = await db
      .delete(userLutsTable)
      .where(and(eq(userLutsTable.id, id), eq(userLutsTable.user_id, req.userId!)))
      .returning({ id: userLutsTable.id });
    if (deleted.length === 0) {
      res.status(404).json({ error: "Saved LUT not found." });
      return;
    }
    res.json({ deleted: true });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Failed to delete the LUT.";
    req.log.error({ err: message }, "[lut] delete failed");
    res.status(500).json({ error: message });
  }
});

