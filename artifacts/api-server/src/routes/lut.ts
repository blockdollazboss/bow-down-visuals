/* ── LUT parsing / validation ───────────────────────────────────────────── */

export interface ParsedLut {
  format: "cube" | "3dl";
  title: string;
  size: number;
  /** Normalized .cube text, ready for ffmpeg's lut3d filter. */
  cubeText: string;
}

export class LutValidationError extends Error {}

function parseCube(text: string): Omit<ParsedLut, "format" | "cubeText"> {
  const lines = text.split(/\r?\n/);
  let title = "Untitled LUT";
  let size = 0;
  const dataLines: string[] = [];

  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const upper = line.toUpperCase();
    if (upper.startsWith("TITLE")) {
      const m = line.match(/"([^"]*)"/);
      if (m) title = m[1].slice(0, 120);
      continue;
    }
    if (upper.startsWith("LUT_3D_SIZE")) {
      const n = parseInt(line.split(/\s+/)[1] ?? "", 10);
      if (!Number.isInteger(n) || n < 2 || n > 64) {
        throw new LutValidationError(
          `Invalid LUT_3D_SIZE "${line}". Expected an integer between 2 and 64.`,
        );
      }
      size = n;
      continue;
    }
    if (
      upper.startsWith("LUT_1D_SIZE") ||
      upper.startsWith("DOMAIN_MIN") ||
      upper.startsWith("DOMAIN_MAX") ||
      upper.startsWith("LUT_1D_INPUT_RANGE") ||
      upper.startsWith("LUT_3D_INPUT_RANGE")
    ) {
      continue;
    }
    dataLines.push(line);
  }

  if (!size) throw new LutValidationError("Missing LUT_3D_SIZE header — not a valid .cube file.");
  const expected = size * size * size;
  if (dataLines.length < expected) {
    throw new LutValidationError(
      `Truncated LUT data: expected ${expected.toLocaleString("en-US")} RGB triplets for LUT_3D_SIZE ${size}, found ${dataLines.length.toLocaleString("en-US")}.`,
    );
  }
  if (dataLines.length > expected) {
    throw new LutValidationError(
      `Too many data lines: expected ${expected.toLocaleString("en-US")} RGB triplets, found ${dataLines.length.toLocaleString("en-US")}.`,
    );
  }
  for (let i = 0; i < dataLines.length; i++) {
    const parts = dataLines[i].split(/\s+/).filter(Boolean);
    if (parts.length !== 3 || parts.some((p) => !/^-?\d+(\.\d+)?$/.test(p))) {
      throw new LutValidationError(`Malformed RGB triplet on data line ${i + 1}: "${dataLines[i].slice(0, 60)}".`);
    }
    for (const p of parts) {
      const v = parseFloat(p);
      if (v < -0.02 || v > 1.02) {
        throw new LutValidationError(
          `LUT value out of range on data line ${i + 1}: values must be between 0 and 1.`,
        );
      }
    }
  }
  return { title, size };
}

/** Parse an IRIDAS .3dl file and normalize it to .cube text. */
function parse3dl(text: string): Omit<ParsedLut, "format" | "cubeText"> & { cubeText: string } {
  const dataLines: string[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    dataLines.push(line);
  }
  if (dataLines.length < 8) {
    throw new LutValidationError("Not a valid .3dl file: expected RGB triplet data lines.");
  }
  const n = Math.round(Math.cbrt(dataLines.length));
  if (n < 4 || n > 64 || n * n * n !== dataLines.length) {
    throw new LutValidationError(
      `Invalid .3dl data: ${dataLines.length.toLocaleString("en-US")} lines is not a perfect cube (n³). Supported lattice sizes: 4–64.`,
    );
  }
  // 3dl files are commonly 0–1023; normalize to 0–1.
  let maxSeen = 0;
  const triples: number[][] = dataLines.map((line, i) => {
    const parts = line.split(/\s+/).filter(Boolean);
    if (parts.length !== 3 || parts.some((p) => !/^-?\d+(\.\d+)?$/.test(p))) {
      throw new LutValidationError(`Malformed RGB triplet on .3dl line ${i + 1}.`);
    }
    const vals = parts.map(Number);
    for (const v of vals) maxSeen = Math.max(maxSeen, v);
    return vals;
  });
  const scale = maxSeen > 1.5 ? 1023 : 1;
  const out: string[] = [
    'TITLE "Converted from .3dl — Bow Down Visuals"',
    `LUT_3D_SIZE ${n}`,
    "DOMAIN_MIN 0.0 0.0 0.0",
    "DOMAIN_MAX 1.0 1.0 1.0",
    "",
  ];
  for (const [r, g, b] of triples) {
    out.push(
      `${Math.min(1, Math.max(0, r! / scale)).toFixed(6)} ${Math.min(1, Math.max(0, g! / scale)).toFixed(6)} ${Math.min(1, Math.max(0, b! / scale)).toFixed(6)}`,
    );
  }
  return { title: "Converted .3dl LUT", size: n, cubeText: out.join("\n") + "\n" };
}

/** Validate an uploaded LUT buffer. Throws LutValidationError with a user-facing message. */
export function validateLutBuffer(buffer: Buffer, originalName: string): ParsedLut {
  if (!buffer || buffer.length < 20) {
    throw new LutValidationError("That file is empty or too small to be a LUT.");
  }
  if (buffer.length > LUT_MAX_BYTES) {
    throw new LutValidationError("That LUT file is too large (max 5 MB).");
  }
  const text = buffer.toString("utf8");
  if (text.includes("\uFFFD")) {
    throw new LutValidationError("That file isn't readable LUT text — it may be binary or corrupted.");
  }
  const ext = (originalName.split(".").pop() ?? "").toLowerCase();
  if (ext === "3dl") {
    const parsed = parse3dl(text);
    return { format: "3dl", ...parsed };
  }
  if (ext === "cube" || ext === "") {
    const parsed = parseCube(text);
    return { format: "cube", title: parsed.title, size: parsed.size, cubeText: text };
  }
  throw new LutValidationError(`Unsupported LUT format ".${ext}" — upload a .cube or .3dl file.`);
}

/* ── LUT resolution ───────────────────────────────────────────────────────
   Every mutating endpoint accepts the LUT as: uploaded file > presetId >
   saved lutId. Returns the normalized .cube text + a display name. */
async function resolveLut(
  req: { file?: Express.Multer.File; body: Record<string, unknown>; userId?: string },
  workDir: string,
): Promise<{ cubePath: string; displayName: string }> {
  const body = req.body ?? {};
  const presetId = typeof body.presetId === "string" ? body.presetId : "";
  const lutId = typeof body.lutId === "string" ? body.lutId : "";
  const lutFile = uploadedFile(req, "lut");

  if (lutFile) {
    const parsed = validateLutBuffer(lutFile.buffer, lutFile.originalname);
    const cubePath = join(workDir, `lut-${randomUUID()}.cube`);
    await writeFile(cubePath, parsed.cubeText);
    return { cubePath, displayName: parsed.title };
  }
  if (presetId) {
    const preset = housePresetById(presetId);
    if (!preset) throw new LutValidationError(`Unknown preset "${presetId}".`);
    const cubePath = join(workDir, `lut-${randomUUID()}.cube`);
    await writeFile(cubePath, await readFile(join(LUTS_DIR, `${preset.id}.cube`), "utf8"));
    return { cubePath, displayName: preset.name };
  }
  if (lutId) {
    if (!req.userId) throw new LutValidationError("Sign in to use a saved LUT.");
    const [row] = await db
      .select()
      .from(userLutsTable)
      .where(and(eq(userLutsTable.id, lutId), eq(userLutsTable.user_id, req.userId)))
      .limit(1);
    if (!row) throw new LutValidationError("That saved LUT wasn't found.");
    const storageUrl = await refreshSupabaseStorageUrl(row.storage_ref);
    const dl = await fetch(storageUrl, { signal: AbortSignal.timeout(60_000) });
    if (!dl.ok) throw new Error("Could not download the saved LUT.");
    const parsed = validateLutBuffer(
      Buffer.from(await dl.arrayBuffer()),
      row.format === "3dl" ? "saved.3dl" : "saved.cube",
    );
    const cubePath = join(workDir, `lut-${randomUUID()}.cube`);
    await writeFile(cubePath, parsed.cubeText);
    return { cubePath, displayName: row.name };
  }
  throw new LutValidationError("No LUT provided — upload a .cube/.3dl file or pick a preset.");
}

/** Grab an uploaded file by field name — works with multer .single() and .fields(). */
function uploadedFile(req: unknown, field: string): Express.Multer.File | undefined {
  const r = req as {
    file?: Express.Multer.File;
    files?: Express.Multer.File[] | Record<string, Express.Multer.File[]>;
  };
  if (Array.isArray(r.files)) return r.files.find((f) => f.fieldname === field);
  return r.files?.[field]?.[0] ?? (r.file?.fieldname === field ? r.file : undefined);
}

/** Fetch the source video (uploaded file or videoUrl) into the work dir. */
async function fetchVideo(
  req: unknown,
  workDir: string,
  body: Record<string, unknown>,
): Promise<string> {
  const inputPath = join(workDir, "input.mp4");
  const videoFile = uploadedFile(req, "video") ?? uploadedFile(req, "clip");
  if (videoFile) {
    if (!videoFile.mimetype.startsWith("video/")) {
      throw new LutValidationError("The uploaded clip isn't a video file.");
    }
    await writeFile(inputPath, videoFile.buffer);
    return inputPath;
  }
  let videoUrl = typeof body.videoUrl === "string" ? body.videoUrl.trim() : "";
  if (!videoUrl) throw new LutValidationError("No video provided — upload a clip or pass videoUrl.");
  if (videoUrl.length > 4096) throw new LutValidationError("videoUrl is too long.");
  // Accept supabase:// storage refs as well as signed/public URLs.
  videoUrl = await refreshSupabaseStorageUrl(videoUrl);
  const res = await fetch(videoUrl, { signal: AbortSignal.timeout(180_000) });
  if (!res.ok) throw new Error("Could not download the video (check the URL).");
  await writeFile(inputPath, Buffer.from(await res.arrayBuffer()));
  return inputPath;
}

type JsonResponder = { status: (code: number) => { json: (body: unknown) => void } };

function isLutValidationError(err: unknown): err is LutValidationError {
  return err instanceof LutValidationError;
}

function sendLutError(res: JsonResponder, err: unknown, req: { log: { error: (obj: unknown, msg: string) => void } }, tag: string): void {
  if (isLutValidationError(err)) {
    res.status(400).json({ error: err.message });
    return;
  }
  const message = err instanceof Error ? err.message : "Request failed.";
  req.log.error({ err: message }, tag);
  res.status(500).json({ error: message });
}

