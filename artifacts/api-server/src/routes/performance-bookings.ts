/**
 * Book the Artist (#158) — performance bookings with escrow.
 *
 * The promoter/venue-facing door of Paid Bookings: a promoter books an
 * artist for a show (date, venue facts, fee), the artist accepts, the
 * promoter funds the fee into escrow (the sponsors escrow pattern —
 * Stripe Checkout, or the sandbox stand-in when no Stripe key is
 * configured), the show happens, the artist marks it complete, and the
 * promoter releases the escrow. Bow Down Visuals keeps 15% of the fee
 * at release (PERFORMANCE_BOOKING_FEE_BPS); the promoter never pays
 * more than the agreed fee.
 *
 * Every record carries its plain-words terms summary (#164),
 * generated by lib/performance-bookings from the agreed facts at
 * creation and attached to the row — what either side reads is what
 * the money moves on.
 *
 * Money is REAL dollars via Stripe — never Visual Bucs. Creating,
 * answering, listing, completing, and releasing are pure UI actions
 * (no credit charge); only the escrow funding moves money.
 *
 * Raw SQL via db.execute, like routes/storefront.ts and
 * routes/generate/sponsors.ts (pg-mem parity + one access shape).
 */

const router = Router();

export function isStripeConfigured(): boolean {
  return !!process.env["STRIPE_SECRET_KEY"];
}

function uuidParam(raw: unknown): string | null {
  const v = Array.isArray(raw) ? raw[0] : raw;
  return typeof v === "string" && z.string().uuid().safeParse(v).success ? v : null;
}

/* ── Row + DTO ─────────────────────────────────────────────────────── */

interface BookingRow {
  id: string;
  profile_id: string;
  artist_user_id: string;
  artist_name: string;
  promoter_user_id: string;
  promoter_name: string;
  event_title: string;
  event_date: string;
  venue_name: string;
  venue_address: string;
  venue_city: string;
  fee_cents: number;
  terms: PerformanceBookingTerms | string;
  plain_words: string;
  notes: string | null;
  status: string;
  escrow_status: string;
  stripe_session_id: string | null;
  platform_fee_cents: number | null;
  artist_payout_cents: number | null;
  paid_at: string | null;
  created_at: string;
  updated_at: string;
}

const BOOKING_COLS = `
  id, profile_id, artist_user_id, artist_name, promoter_user_id, promoter_name,
  event_title, event_date, venue_name, venue_address, venue_city,
  fee_cents, terms, plain_words, notes, status, escrow_status,
  stripe_session_id, platform_fee_cents, artist_payout_cents, paid_at,
  created_at, updated_at
`;

export interface PerformanceBookingDto {
  id: string;
  profileId: string;
  artistUserId: string;
  artistName: string;
  promoterUserId: string;
  promoterName: string;
  eventTitle: string;
  eventDate: string;
  venueName: string;
  venueAddress: string;
  venueCity: string;
  feeCents: number;
  terms: PerformanceBookingTerms;
  plainWords: string;
  notes: string | null;
  status: string;
  escrowStatus: string;
  platformFeeCents: number | null;
  artistPayoutCents: number | null;
  paidAt: string | null;
  /** The split the release will apply at the current fee — shown to
   *  both sides before any money moves, so the release is never a
   *  surprise. Equals the stored columns once paid. */
  feePreview: { feeCents: number; netCents: number };
  role: "promoter" | "artist" | null;
  createdAt: string;
  updatedAt: string;
}

function parseTerms(raw: PerformanceBookingTerms | string): PerformanceBookingTerms {
  if (typeof raw === "string") {
    try {
      return JSON.parse(raw) as PerformanceBookingTerms;
    } catch {
      return { performance: "" };
    }
  }
  return raw;
}

export function toBookingDto(r: BookingRow, viewerUserId: string | null): PerformanceBookingDto {
  return {
    id: r.id,
    profileId: r.profile_id,
    artistUserId: r.artist_user_id,
    artistName: r.artist_name,
    promoterUserId: r.promoter_user_id,
    promoterName: r.promoter_name,
    eventTitle: r.event_title,
    eventDate: new Date(r.event_date).toISOString(),
    venueName: r.venue_name,
    venueAddress: r.venue_address,
    venueCity: r.venue_city,
    feeCents: Number(r.fee_cents),
    terms: parseTerms(r.terms),
    plainWords: r.plain_words,
    notes: r.notes,
    status: r.status,
    escrowStatus: r.escrow_status,
    platformFeeCents: r.platform_fee_cents,
    artistPayoutCents: r.artist_payout_cents,
    paidAt: r.paid_at,
    feePreview: performanceFeeSplit(Number(r.fee_cents)),
    role: viewerUserId === r.promoter_user_id
      ? "promoter"
      : viewerUserId === r.artist_user_id
        ? "artist"
        : null,
    createdAt: new Date(r.created_at).toISOString(),
    updatedAt: new Date(r.updated_at).toISOString(),
  };
}

async function findBooking(bookingId: string): Promise<BookingRow | null> {
  const result = await db.execute(sql`
    SELECT ${sql.raw(BOOKING_COLS)} FROM performance_bookings WHERE id = ${bookingId} LIMIT 1
  `);
  return (result.rows[0] as unknown as BookingRow) ?? null;
}

function roleOf(row: BookingRow, userId: string): "promoter" | "artist" | null {
  if (row.promoter_user_id === userId) return "promoter";
  if (row.artist_user_id === userId) return "artist";
  return null;
}

/** Shared guard for the action endpoints: the booking must exist, the
 *  caller must be the participant the action belongs to, and the
 *  lifecycle must allow the step. Answers the honest error and
 *  returns null when any of that fails. */
async function guardAction(
  req: { userId?: string },
  res: { status: (n: number) => { json: (b: unknown) => void } },
  bookingId: string | null,
  action: PerformanceBookingAction,
): Promise<BookingRow | null> {
  if (!bookingId) {
    res.status(400).json({ error: "Invalid booking id." });
    return null;
  }
  const row = await findBooking(bookingId);
  if (!row) {
    res.status(404).json({ error: "Booking not found." });
    return null;
  }
  const role = roleOf(row, req.userId!);
  if (!role) {
    res.status(403).json({ error: "Only the promoter and the artist on this booking can act on it." });
    return null;
  }
  const actor = ACTION_ACTOR[action];
  if (actor !== "either" && actor !== role) {
    res.status(403).json({
      error: actor === "artist"
        ? "Only the artist can take this step."
        : "Only the promoter can take this step.",
    });
    return null;
  }
  const check = canTakeAction(row.status, action);
  if (!check.ok) {
    res.status(409).json({ error: check.message });
    return null;
  }
  return row;
}

/* ── CREATE: a promoter books the artist ───────────────────────────── */

export const createPerformanceBookingSchema = z.object({
  profileId: z.string().uuid(),
  promoterName: z.string().trim().min(1, "Say who is booking — a venue, company, or your name.").max(160),
  eventTitle: z.string().trim().min(1, "Name the show.").max(200),
  eventDate: z.string().datetime({ message: "The show date must be an ISO date/time." }),
  venueName: z.string().trim().min(1, "Name the venue.").max(200),
  venueAddress: z.string().trim().min(1, "Give the venue address.").max(300),
  venueCity: z.string().trim().min(1, "Give the venue city.").max(120),
  feeCents: z.number().int().min(100, "The fee must be at least $1.").max(100_000_000),
  terms: z.object({
    performance: z.string().trim().min(1, "Say what the artist is booked to do.").max(500),
    setLengthMin: z.number().int().min(1).max(1440).nullable().optional(),
    productionNotes: z.string().trim().max(1000).nullable().optional(),
    cancellationTerms: z.string().trim().max(1000).nullable().optional(),
  }),
  notes: z.string().trim().max(2000).optional(),
});

router.post("/performance-bookings", requireAuth, publicApiLimiter, async (req, res) => {
  const parsed = createPerformanceBookingSchema.safeParse(req.body ?? {});
  if (!parsed.success) {
    res.status(400).json({
      error: "That booking is missing something.",
      details: parsed.error.issues.map((i) => i.message),
    });
    return;
  }
  const d = parsed.data;
  try {
    const prof = await db.execute(sql`
      SELECT id, user_id::text AS user_id, display_name
      FROM creator_profiles WHERE id = ${d.profileId} LIMIT 1
    `);
    const profile = prof.rows[0] as { id: string; user_id: string; display_name: string } | undefined;
    if (!profile) {
      res.status(404).json({ error: "That artist profile could not be found." });
      return;
    }
    if (profile.user_id === req.userId) {
      res.status(400).json({ error: "OWN_PROFILE", message: "You can't book yourself — this door is for promoters and venues booking you." });
      return;
    }
    if (new Date(d.eventDate).getTime() <= Date.now()) {
      res.status(400).json({ error: "The show date has to be in the future." });
      return;
    }
    const terms: PerformanceBookingTerms = {
      performance: d.terms.performance,
      setLengthMin: d.terms.setLengthMin ?? null,
      productionNotes: d.terms.productionNotes ?? null,
      cancellationTerms: d.terms.cancellationTerms ?? null,
    };
    /* The plain-words summary is generated NOW, from the agreed
       facts, and attached to the record — never written by hand. */
    const plainWords = buildPlainWordsTerms({
      artistName: profile.display_name,
      promoterName: d.promoterName,
      eventTitle: d.eventTitle,
      eventDate: d.eventDate,
      venueName: d.venueName,
      venueAddress: d.venueAddress,
      venueCity: d.venueCity,
      feeCents: d.feeCents,
      terms,
    });
    const id = randomUUID();
    await db.execute(sql`
      INSERT INTO performance_bookings
        (id, profile_id, artist_user_id, artist_name, promoter_user_id, promoter_name,
         event_title, event_date, venue_name, venue_address, venue_city,
         fee_cents, terms, plain_words, notes, status, escrow_status)
      VALUES (${id}, ${profile.id}, ${profile.user_id}, ${profile.display_name},
              ${req.userId!}, ${d.promoterName},
              ${d.eventTitle}, ${d.eventDate}, ${d.venueName}, ${d.venueAddress}, ${d.venueCity},
              ${d.feeCents}, ${JSON.stringify(terms)}::jsonb, ${plainWords}, ${d.notes ?? null},
              'proposed', 'unfunded')
    `);
    const row = await findBooking(id);
    logger.info({ bookingId: id, profileId: profile.id, feeCents: d.feeCents }, "[performance-bookings] booking proposed");
    res.status(201).json({ booking: toBookingDto(row!, req.userId!) });
  } catch (err) {
    logger.error({ err }, "[performance-bookings] create failed");
    res.status(500).json({ error: "Could not create that booking — try again." });
  }
});

/* ── LIST + DETAIL ─────────────────────────────────────────────────── */

router.get("/performance-bookings", requireAuth, async (req, res) => {
  try {
    const r = await db.execute(sql`
      SELECT ${sql.raw(BOOKING_COLS)} FROM performance_bookings
      WHERE promoter_user_id = ${req.userId!} OR artist_user_id = ${req.userId!}
      ORDER BY created_at DESC
      LIMIT 200
    `);
    const bookings = (r.rows as unknown as BookingRow[]).map((row) => toBookingDto(row, req.userId!));
    res.json({
      bookings,
      counts: {
        proposed: bookings.filter((b) => b.status === "proposed").length,
        active: bookings.filter((b) => ["accepted", "funded", "completed"].includes(b.status)).length,
        paid: bookings.filter((b) => b.status === "paid").length,
        closed: bookings.filter((b) => ["declined", "cancelled"].includes(b.status)).length,
      },
      note: "Performance fees are real money held in escrow until the show is done and the promoter releases them. Bow Down Visuals keeps 15% of the fee at release.",
    });
  } catch (err) {
    logger.error({ err }, "[performance-bookings] list failed");
    res.status(500).json({ error: "Could not load your bookings." });
  }
});

