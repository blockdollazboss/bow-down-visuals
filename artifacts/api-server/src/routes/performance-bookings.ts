/* ── RESPOND: the artist accepts or declines ────────────────────────── */

export const respondSchema = z.object({ action: z.enum(["accept", "decline"]) });

router.post("/performance-bookings/:id/respond", requireAuth, publicApiLimiter, async (req, res) => {
  const parsed = respondSchema.safeParse(req.body ?? {});
  if (!parsed.success) {
    res.status(400).json({ error: "Say whether you accept or decline." });
    return;
  }
  try {
    const row = await guardAction(req, res, uuidParam(req.params["id"]), parsed.data.action);
    if (!row) return;
    const to = parsed.data.action === "accept" ? "accepted" : "declined";
    /* Claim the answer: only a still-proposed booking flips, so a
       racing double-answer can't tell the promoter twice. */
    const flipped = await db.execute(sql`
      UPDATE performance_bookings SET status = ${to}, updated_at = NOW()
      WHERE id = ${row.id} AND status = 'proposed'
      RETURNING id
    `);
    if (flipped.rows.length === 0) {
      res.status(409).json({ error: "This booking just changed — refresh and try again." });
      return;
    }
    await tellBookingParty({
      userId: row.promoter_user_id,
      kind: parsed.data.action === "accept" ? "performance_booking_accepted" : "performance_booking_declined",
      title: parsed.data.action === "accept" ? "Booking accepted" : "Booking declined",
      body: parsed.data.action === "accept"
        ? `${row.artist_name} accepted your booking for "${row.event_title}" (${moneyCents(Number(row.fee_cents))}). Fund the escrow to lock it in.`
        : `${row.artist_name} declined your booking for "${row.event_title}". No money moved.`,
      link: await bookingLink(row),
    });
    const fresh = await findBooking(row.id);
    res.json({ booking: toBookingDto(fresh!, req.userId!) });
  } catch (err) {
    logger.error({ err }, "[performance-bookings] respond failed");
    res.status(500).json({ error: "Could not record your answer — try again." });
  }
});

/* ── FUND: the promoter puts the fee in escrow ─────────────────────── */

/* Embedded checkout (owner law 2026-10-26: never leave the site):
   "embedded" creates the SAME escrow session in embedded_page
   ui_mode and answers its clientSecret so the promoter pays on the
   page; absent/"hosted" keeps the hosted-URL shape. Honored only
   while the EMBEDDED_CHECKOUT kill switch is on. */
export const fundCheckoutSchema = z.object({
  uiMode: z.enum(["embedded", "hosted"]).optional(),
});

router.post("/performance-bookings/:id/fund", requireAuth, publicApiLimiter, async (req, res) => {
  const bookingId = uuidParam(req.params["id"]);
  const parsed = fundCheckoutSchema.safeParse(req.body ?? {});
  if (!parsed.success) {
    res.status(400).json({ error: "Invalid request." });
    return;
  }
  const embeddedRequested =
    parsed.data.uiMode === "embedded" && isEmbeddedCheckoutEnabled();
  try {
    const row = await guardAction(req, res, bookingId, "fund");
    if (!row) return;
    if (row.escrow_status !== "unfunded") {
      res.status(409).json({ error: `This booking's escrow is already ${row.escrow_status}.` });
      return;
    }
    await db.execute(sql`
      UPDATE performance_bookings SET escrow_status = 'funding', updated_at = NOW() WHERE id = ${row.id}
    `);

    if (!isStripeConfigured()) {
      /* Sandbox mode — no Stripe keys. The promoter "completes" this
         session via /api/performance-bookings/escrow/confirm to
         simulate the money movement, exactly like sponsor escrow. */
      const sessionId = `sandbox_${randomUUID()}`;
      await db.execute(sql`
        UPDATE performance_bookings SET stripe_session_id = ${sessionId} WHERE id = ${row.id}
      `);
      logger.info({ bookingId: row.id, feeCents: row.fee_cents }, "[performance-bookings] escrow funded in SANDBOX mode");
      res.json({
        sandbox: true,
        sessionId,
        feeCents: Number(row.fee_cents),
        message: "Sandbox mode — no real money moved. Confirm to simulate funding.",
      });
      return;
    }

    const prof = await db.execute(sql`
      SELECT slug FROM creator_profiles WHERE id = ${row.profile_id} LIMIT 1
    `);
    const slug = (prof.rows[0] as { slug?: string } | undefined)?.slug;
    const stripe = createGuardedStripeClient();
    const domain = process.env["REPLIT_DOMAINS"]?.split(",")[0];
    const baseUrl = domain ? `https://${domain}` : "http://localhost";
    const successUrl = `${baseUrl}/artist/${slug ?? ""}?booking=${row.id}&funded=1`;
    /* The amount and metadata are identical either way; the
       presentation makes it a different Stripe request, so the
       idempotency key fingerprints the exact parameters below. An
       embedded session takes a return_url (the same funded landing)
       instead of success/cancel URLs; funding still lands via the
       webhook. */
    const sessionParams: Stripe.Checkout.SessionCreateParams = {
      mode: "payment",
      payment_method_types: ["card"],
      line_items: [
        {
          price_data: {
            currency: "usd",
            unit_amount: Number(row.fee_cents),
            product_data: {
              name: `Performance booking escrow — ${row.event_title}`,
              description: `Fee for ${row.artist_name} — held in escrow until the show is complete and released`,
            },
          },
          quantity: 1,
        },
      ],
      metadata: {
        performance_booking_id: row.id,
        performance_escrow: "true",
        promoter_user_id: req.userId!,
        amount_cents: String(row.fee_cents),
      },
      ...(embeddedRequested
        ? { ui_mode: "embedded_page" as const, return_url: successUrl }
        : {
            success_url: successUrl,
            cancel_url: `${baseUrl}/artist/${slug ?? ""}?booking=${row.id}&funded=0`,
          }),
    };
    const idempotencyKey = buildPerformanceEscrowCheckoutKey({
      promoterUserId: req.userId!,
      bookingId: row.id,
      feeCents: Number(row.fee_cents),
      requestParams: sessionParams,
    });
    const session = await stripe.checkout.sessions.create(sessionParams, { idempotencyKey });
    if (embeddedRequested && !session.client_secret) {
      /* An embedded session without a client secret cannot be
         mounted — throwing lands in the catch below, which resets
         the escrow to unfunded exactly like a failed creation. */
      throw new Error("Checkout session did not return a client secret");
    }
    await db.execute(sql`
      UPDATE performance_bookings SET stripe_session_id = ${session.id} WHERE id = ${row.id}
    `);
    if (embeddedRequested) {
      res.json({
        sandbox: false,
        checkoutUrl: null,
        clientSecret: session.client_secret,
        uiMode: "embedded",
        sessionId: session.id,
      });
      return;
    }
    res.json({ sandbox: false, checkoutUrl: session.url, sessionId: session.id });
  } catch (err) {
    logger.error({ err }, "[performance-bookings] failed to create escrow funding session");
    if (bookingId) {
      await db.execute(sql`
        UPDATE performance_bookings SET escrow_status = 'unfunded'
        WHERE id = ${bookingId} AND escrow_status = 'funding'
      `).catch(() => undefined);
    }
    res.status(500).json({ error: "Could not start the funding flow — try again." });
  }
});

/* Mark an escrow funded — shared by the Stripe webhook (real money)
   and the sandbox confirm endpoint (test mode). Idempotent on
   session id, exactly like markEscrowFunded for sponsor deals. */
export async function markPerformanceEscrowFunded(
  bookingId: string,
  sessionId: string,
  paymentIntentId: string | null,
): Promise<{ ok: boolean; reason?: string }> {
  const row = await findBooking(bookingId);
  if (!row) return { ok: false, reason: "booking-not-found" };
  if (row.escrow_status === "funded" && row.stripe_session_id === sessionId) {
    return { ok: true, reason: "already-funded" };
  }
  if (row.escrow_status !== "funding" && row.escrow_status !== "unfunded") {
    return { ok: false, reason: `bad-state:${row.escrow_status}` };
  }
  if (row.status !== "accepted" && row.status !== "funded") {
    return { ok: false, reason: `bad-status:${row.status}` };
  }
  /* The flip claims the from-states: concurrent webhook + confirm
     calls land it exactly once, and only the lander tells the artist. */
  const flipped = await db.execute(sql`
    UPDATE performance_bookings
    SET escrow_status = 'funded', status = 'funded',
        stripe_session_id = ${sessionId},
        stripe_payment_intent_id = ${paymentIntentId},
        updated_at = NOW()
    WHERE id = ${bookingId} AND escrow_status IN ('funding', 'unfunded')
    RETURNING id
  `);
  if (flipped.rows.length === 0) {
    const now = await findBooking(bookingId);
    if (now?.escrow_status === "funded") return { ok: true, reason: "already-funded" };
    return { ok: false, reason: `bad-state:${now?.escrow_status ?? "gone"}` };
  }
  logger.info({ bookingId, sessionId }, "[performance-bookings] escrow funded");
  await tellBookingParty({
    userId: row.artist_user_id,
    kind: "performance_escrow_funded",
    title: "Booking escrow funded",
    body: `The promoter funded the escrow for "${row.event_title}" (${moneyCents(Number(row.fee_cents))}). The show is locked in.`,
    link: await bookingLink(row),
  });
  return { ok: true };
}

export const escrowConfirmSchema = z.object({
  bookingId: z.string().uuid(),
  sessionId: z.string().min(1).max(200),
});

/* POST /api/performance-bookings/escrow/confirm — SANDBOX ONLY.
   Simulates a successful Stripe payment for a sandbox funding
   session. Refuses to run when real Stripe keys are configured
   (the webhook owns that path then). */
router.post("/performance-bookings/escrow/confirm", requireAuth, publicApiLimiter, async (req, res) => {
  if (isStripeConfigured()) {
    res.status(400).json({ error: "Sandbox confirm is disabled — Stripe is configured; fund via Checkout." });
    return;
  }
  const parsed = escrowConfirmSchema.safeParse(req.body ?? {});
  if (!parsed.success) {
    res.status(400).json({ error: "Invalid request." });
    return;
  }
  try {
    const row = await findBooking(parsed.data.bookingId);
    if (!row) {
      res.status(404).json({ error: "Booking not found." });
      return;
    }
    if (row.promoter_user_id !== req.userId) {
      res.status(403).json({ error: "Only the promoter can confirm funding." });
      return;
    }
    if (!row.stripe_session_id || !row.stripe_session_id.startsWith("sandbox_") || row.stripe_session_id !== parsed.data.sessionId) {
      res.status(400).json({ error: "Unknown sandbox session." });
      return;
    }
    const result = await markPerformanceEscrowFunded(row.id, parsed.data.sessionId, null);
    if (!result.ok) {
      res.status(409).json({ error: `Could not confirm funding (${result.reason}).` });
      return;
    }
    res.json({ success: true, escrowStatus: "funded" });
  } catch (err) {
    logger.error({ err }, "[performance-bookings] sandbox escrow confirm failed");
    res.status(500).json({ error: "Could not confirm funding — try again." });
  }
});

