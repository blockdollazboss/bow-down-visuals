/** Self-hosted creator library stylesheet (generated by fetch-creator-fonts.py). */
export const CREATOR_FONTS_CSS_HREF = "/fonts/creator-fonts.css";

/** Inject a font stylesheet once (idempotent per element id). */
export function ensureFontStylesheet(id: string, href: string): void {
  if (typeof document === "undefined") return;
  if (document.getElementById(id)) return;
  const link = document.createElement("link");
  link.id = id;
  link.rel = "stylesheet";
  link.href = href;
  document.head.appendChild(link);
}

export function ensureCaptionFonts(): void {
  ensureFontStylesheet("bdv-caption-fonts", CAPTION_FONTS_CSS_URL);
}

export function ensureLibraryFonts(): void {
  ensureFontStylesheet("bdv-library-fonts", LIBRARY_FONTS_CSS_URL);
}

/** Load the self-hosted creator font library (64 families, local files). */
export function ensureCreatorFonts(): void {
  ensureFontStylesheet("bdv-creator-fonts", CREATOR_FONTS_CSS_HREF);
}
