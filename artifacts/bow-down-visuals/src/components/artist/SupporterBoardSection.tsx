import { useEffect, useState } from "react";
import { Link } from "wouter";
import { Trophy, AlertTriangle, RotateCcw, Crown, EyeOff, Eye } from "lucide-react";
import {
  fetchSupporterBoard,
  setSupporterOptOut,
  supportBreakdown,
  supporterBoardViewState,
  supporterDisplayName,
  SUPPORTER_BOARD_COPY,
  type SupporterBoardDto,
  type SupporterBoardLoadStatus,
  type SupporterPeriod,
} from "@/lib/supporter-board";
import { fetchMyProfile } from "@/lib/artist-profiles";

/* ─── Top Supporters — public profile section (Wave-4 #49 + N6) ─────────
   The creator's top supporters for the period, ranked from real
   support only (purchases, landed VB tips, paid memberships, ticketed
   shows — the API's ledgers, never follows or invented scores). The
   basis line on the board is generated by the server from the period
   window, so it always says exactly what the ranking counts.
   Viewer side: a signed-in supporter sees their own standing and can
   leave (opt out) or rejoin the board right here — their standing is
   only ever shown where the creator has the board ON. An OFF board is
   hidden from visitors; its owner sees the off notice instead. An
   enabled-but-empty board shows the honest empty copy.
   Themed through the profile's --ap-* tokens, which carry designed
   light AND dark palettes (themeVars) — both themes by design. */

export default function SupporterBoardSection({ slug }: { slug: string }) {
  const [board, setBoard] = useState<SupporterBoardDto | null>(null);
  const [status, setStatus] = useState<SupporterBoardLoadStatus>("loading");
  const [period, setPeriod] = useState<SupporterPeriod>("month");
  const [isOwner, setIsOwner] = useState(false);
  const [retryNonce, setRetryNonce] = useState(0);
  const [optBusy, setOptBusy] = useState(false);
  const [optError, setOptError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    setStatus("loading");
    (async () => {
      try {
        const dto = await fetchSupporterBoard(slug, period);
        if (!cancelled) {
          setBoard(dto);
          setStatus("ready");
        }
      } catch {
        if (!cancelled) setStatus("error");
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [slug, period, retryNonce]);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const mine = await fetchMyProfile();
        if (!cancelled) setIsOwner(!!mine && mine.slug === slug);
      } catch {
        if (!cancelled) setIsOwner(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [slug]);

  const view = supporterBoardViewState({ status, board, isOwner });
  if (view === "loading" || view === "hidden") return null;

  const toggleOptOut = async (optedOut: boolean) => {
    setOptBusy(true);
    setOptError(null);
    try {
      await setSupporterOptOut(slug, optedOut);
      setRetryNonce((n) => n + 1);
    } catch {
      setOptError("Couldn't update your board preference — try again.");
    } finally {
      setOptBusy(false);
    }
  };

  const viewer = board?.viewer ?? null;

  return (
    <section className="ap-section" style={{ padding: "var(--ap-pad)" }} data-testid="supporter-board">
      <div className="mb-1 flex flex-wrap items-center gap-2">
        <Trophy className="h-5 w-5" style={{ color: "var(--ap-primary)" }} />
        <h2
          className="text-xl font-bold tracking-wide sm:text-2xl"
          style={{ fontFamily: "var(--ap-heading-font)", color: "var(--ap-text)" }}
        >
          Top Supporters
        </h2>
        <div className="ml-auto flex overflow-hidden rounded-full" style={{ border: "1px solid var(--ap-border)" }}>
          {(["month", "all"] as SupporterPeriod[]).map((p) => (
            <button
              key={p}
              type="button"
              onClick={() => setPeriod(p)}
              className="px-3 py-1 text-xs font-bold transition"
              style={
                period === p
                  ? { backgroundColor: "var(--ap-primary)", color: "#000" }
                  : { color: "var(--ap-muted)", backgroundColor: "transparent" }
              }
              data-testid={`supporter-period-${p}`}
            >
              {p === "month" ? "This month" : "All time"}
            </button>
          ))}
        </div>
      </div>

      {view === "error" && (
        <div
          className="flex flex-col items-center gap-2 rounded-xl px-4 py-6 text-center"
          style={{ border: "1px solid var(--ap-border)", backgroundColor: "var(--ap-card)" }}
        >
          <AlertTriangle className="h-6 w-6" style={{ color: "var(--ap-primary)" }} />
          <p className="text-sm" style={{ color: "var(--ap-text)" }}>
            The supporter board couldn't load right now.
          </p>
          <button
            type="button"
            onClick={() => setRetryNonce((n) => n + 1)}
            className="mt-1 inline-flex items-center gap-2 rounded-full px-5 py-2 text-xs font-bold text-black transition hover:scale-105"
            style={{ backgroundColor: "var(--ap-primary)" }}
          >
            <RotateCcw className="h-3.5 w-3.5" /> Try again
          </button>
        </div>
      )}

      {view === "off" && (
        <div
          className="rounded-xl px-4 py-5 text-center"
          style={{ border: "1px dashed var(--ap-primary)", backgroundColor: "var(--ap-card)" }}
        >
          <p className="text-sm font-semibold" style={{ color: "var(--ap-text)" }}>
            Your supporter board is off.
          </p>
          <p className="mx-auto mt-1 max-w-sm text-xs" style={{ color: "var(--ap-muted)" }}>
            {SUPPORTER_BOARD_COPY.boardOff} Turn it on in your profile setup to recognize the fans who
            support you most.
          </p>
          <Link
            href="/artist-setup"
            className="mt-3 inline-block rounded-full px-5 py-2 text-xs font-bold text-black transition hover:scale-105"
            style={{ backgroundColor: "var(--ap-primary)" }}
          >
            Open board settings
          </Link>
        </div>
      )}

      {(view === "empty" || view === "ready") && board && (
        <>
          <p className="text-xs font-semibold" style={{ color: "var(--ap-muted)" }}>
            {board.basis}
          </p>
          <p className="mb-3 text-xs" style={{ color: "var(--ap-muted)" }}>
            {SUPPORTER_BOARD_COPY.rankedFromRealSupport} {SUPPORTER_BOARD_COPY.x100Explainer}
          </p>

          {view === "empty" && (
            <div
              className="rounded-xl px-4 py-6 text-center"
              style={{ border: "1px solid var(--ap-border)", backgroundColor: "var(--ap-card)" }}
              data-testid="supporter-board-empty"
            >
              <Trophy className="mx-auto h-6 w-6" style={{ color: "var(--ap-primary)" }} />
              <p className="mt-2 text-sm" style={{ color: "var(--ap-text)" }}>
                {board.emptyCopy}
              </p>
            </div>
          )}

          {view === "ready" && (
            <ol className="grid gap-2">
              {board.entries.map((e) => (
                <li
                  key={e.userId}
                  className="flex items-center gap-3 rounded-xl px-4 py-3"
                  style={{ border: "1px solid var(--ap-border)", backgroundColor: "var(--ap-card)" }}
                  data-testid={`supporter-rank-${e.rank}`}
                >
                  <span
                    className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full text-sm font-black"
                    style={{ backgroundColor: "var(--ap-primary)", color: "#000" }}
                  >
                    {e.rank}
                  </span>
                  {e.avatarUrl ? (
                    <img src={e.avatarUrl} alt="" className="h-10 w-10 shrink-0 rounded-full object-cover" />
                  ) : (
                    <span
                      className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full text-sm font-bold"
                      style={{ border: "1px solid var(--ap-border)", color: "var(--ap-muted)" }}
                    >
                      {supporterDisplayName(e).slice(0, 1)}
                    </span>
                  )}
                  <div className="min-w-0 flex-1">
                    {e.profileSlug ? (
                      <Link
                        href={`/artist/${e.profileSlug}`}
                        className="block truncate text-sm font-bold hover:underline"
                        style={{ color: "var(--ap-text)" }}
                      >
                        {supporterDisplayName(e)}
                      </Link>
                    ) : (
                      <span className="block truncate text-sm font-bold" style={{ color: "var(--ap-text)" }}>
                        {supporterDisplayName(e)}
                      </span>
                    )}
                    <span className="block truncate text-xs" style={{ color: "var(--ap-muted)" }}>
                      {supportBreakdown(e).join(" · ") || "Recognized supporter"}
                    </span>
                  </div>
                  {e.badge && (
                    <span
                      className="inline-flex shrink-0 items-center gap-1 rounded-full px-3 py-1 text-[11px] font-black"
                      style={
                        e.badge.tier === "front_row"
                          ? { backgroundColor: "var(--ap-primary)", color: "#000" }
                          : { border: "1px solid var(--ap-primary)", color: "var(--ap-primary)" }
                      }
                      data-testid={`supporter-badge-${e.rank}`}
                    >
                      <Crown className="h-3 w-3" /> {e.badge.label}
                    </span>
                  )}
                </li>
              ))}
            </ol>
          )}

          {board.perksText && (
            <div
              className="mt-3 rounded-xl px-4 py-3"
              style={{ border: "1px solid var(--ap-border)", backgroundColor: "var(--ap-card)" }}
            >
              <p className="text-xs font-bold uppercase tracking-widest" style={{ color: "var(--ap-primary)" }}>
                {SUPPORTER_BOARD_COPY.perksHeading}
              </p>
              <p className="mt-1 whitespace-pre-line text-sm" style={{ color: "var(--ap-text)" }}>
                {board.perksText}
              </p>
            </div>
          )}

          {viewer && !viewer.isCreator && (
            <div
              className="mt-3 flex flex-wrap items-center gap-2 rounded-xl px-4 py-3"
              style={{ border: "1px solid var(--ap-border)", backgroundColor: "var(--ap-card)" }}
              data-testid="supporter-viewer-standing"
            >
              {viewer.optedOut ? (
                <>
                  <p className="flex-1 text-xs" style={{ color: "var(--ap-muted)" }}>
                    You've left this board — your name and badge stay off it. {SUPPORTER_BOARD_COPY.optOut}
                  </p>
                  <button
                    type="button"
                    disabled={optBusy}
                    onClick={() => toggleOptOut(false)}
                    className="inline-flex items-center gap-1.5 rounded-full px-4 py-1.5 text-xs font-bold text-black transition hover:scale-105 disabled:opacity-50"
                    style={{ backgroundColor: "var(--ap-primary)" }}
                  >
                    <Eye className="h-3.5 w-3.5" /> Rejoin the board
                  </button>
                </>
              ) : viewer.standing ? (
                <>
                  <p className="flex-1 text-xs font-semibold" style={{ color: "var(--ap-text)" }}>
                    You're #{viewer.standing.rank} on this board {board.period === "month" ? "this month" : "all time"}
                    {viewer.standing.badge ? ` — ${viewer.standing.badge.label}` : ""}.
                  </p>
                  <button
                    type="button"
                    disabled={optBusy}
                    onClick={() => toggleOptOut(true)}
                    className="inline-flex items-center gap-1.5 rounded-full px-4 py-1.5 text-xs font-bold transition hover:scale-105 disabled:opacity-50"
                    style={{ border: "1px solid var(--ap-border)", color: "var(--ap-muted)" }}
                  >
                    <EyeOff className="h-3.5 w-3.5" /> Leave this board
                  </button>
                </>
              ) : (
                <p className="flex-1 text-xs" style={{ color: "var(--ap-muted)" }}>
                  You're not on this board {board.period === "month" ? "this month" : "yet"} — support this
                  creator with a tip, a purchase, a membership, or a show ticket and you'll rank here.
                </p>
              )}
              {optError && (
                <p className="w-full text-xs text-red-500">{optError}</p>
              )}
            </div>
          )}
        </>
      )}
    </section>
  );
}
