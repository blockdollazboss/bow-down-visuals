#!/usr/bin/env node
/* ── Sound bank registration generator ──────────────────────────────────
 * Reads the rendered sound bank (~/workspace/sound-bank/manifest.json +
 * its WAV tree) and produces the two things the site ships:
 *   1. every WAV copied to public/sound-bank/<relative path> — the same
 *      static-file serving the site's other audio uses (theme MP3 in
 *      public/audio, signature WAVs in public/sounds); the registry
 *      fetches a file lazily, only when a creator assigns/plays it.
 *   2. src/lib/beat-sound-bank-manifest.ts — the registry-shaped manifest
 *      (lib/beat-sounds.ts seam), GENERATED from the bank manifest. Never
 *      hand-edit the output; fix the bank and re-run this script.
 *
 * Registry kind mapping (the sequencer's track kinds + bank-only kinds):
 *   drums, by file stem — kick→kick, snare→snare, clap→clap,
 *     closed-hat→chat, open-hat→ohat, crash→crash, shaker→shk,
 *     perc/rim/snap/tom-low/tom-high→perc
 *   808→b808 · bass→bass · melodic→melodic · fx→fx
 * Bank metadata (category, kit, instrument, note, midi) rides along on
 * every entry so kit grouping and tuned-note names survive registration.
 *
 * Usage: node scripts/generate-sound-bank.mjs [bankDir]
 *   bankDir defaults to ~/workspace/sound-bank.
 */
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const artifactDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bankDir = process.argv[2] ? resolve(process.argv[2]) : join(homedir(), "workspace", "sound-bank");
const publicDir = join(artifactDir, "public", "sound-bank");
const outFile = join(artifactDir, "src", "lib", "beat-sound-bank-manifest.ts");

const DRUM_STEM_KIND = {
  "kick": "kick",
  "snare": "snare",
  "clap": "clap",
  "closed-hat": "chat",
  "open-hat": "ohat",
  "crash": "crash",
  "shaker": "shk",
  "perc": "perc",
  "rim": "perc",
  "snap": "perc",
  "tom-low": "perc",
  "tom-high": "perc",
};
const CATEGORY_KIND = { "808": "b808", "bass": "bass", "melodic": "melodic", "fx": "fx" };

const manifest = JSON.parse(readFileSync(join(bankDir, "manifest.json"), "utf8"));
const sounds = manifest.sounds;
if (!Array.isArray(sounds) || sounds.length !== manifest.count) {
  throw new Error(`bank manifest count mismatch: header ${manifest.count}, entries ${sounds?.length}`);
}

const entries = [];
for (const s of sounds) {
  let kind;
  if (s.kind === "drums") {
    const stem = s.file.split("/").pop().replace(/\.wav$/, "");
    kind = DRUM_STEM_KIND[stem];
    if (!kind) throw new Error(`unmapped drum stem "${stem}" (${s.id})`);
  } else {
    kind = CATEGORY_KIND[s.kind];
    if (!kind) throw new Error(`unmapped bank kind "${s.kind}" (${s.id})`);
  }
  const src = join(bankDir, s.file);
  if (!existsSync(src)) throw new Error(`bank file missing: ${src}`);
  const dest = join(publicDir, s.file);
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(src, dest);
  entries.push({
    id: `bank:${s.id}`,
    name: s.name,
    kind,
    source: "bank",
    url: `/sound-bank/${s.file}`,
    bankCategory: s.category,
    ...(s.kit ? { kit: s.kit } : {}),
    ...(s.instrument ? { instrument: s.instrument } : {}),
    ...(s.note ? { note: s.note } : {}),
    ...(typeof s.midi === "number" ? { midi: s.midi } : {}),
  });
}

const body = entries
  .map((e) => `  ${JSON.stringify(e)},`)
  .join("\n");
const out = `/* ── Sound bank manifest — GENERATED, do not hand-edit ────────────────
 * Generated by scripts/generate-sound-bank.mjs from the rendered bank's
 * manifest.json (~/workspace/sound-bank, 316 original synthesized sounds,
 * 44.1 kHz mono 16-bit WAV). Re-run the script after any bank change.
 * Entry shape is the registry manifest shape of lib/beat-sounds.ts;
 * bankCategory/kit/instrument/note/midi carry the bank's own metadata
 * through registration so kits and tuned-note names are preserved. */
import type { BeatSoundManifestEntry } from "@/lib/beat-sounds";

export const BANK_SOUND_MANIFEST: BeatSoundManifestEntry[] = [
${body}
];
`;
writeFileSync(outFile, out);
console.log(`sound bank: copied + registered ${entries.length} sounds -> public/sound-bank/ + ${outFile}`);
