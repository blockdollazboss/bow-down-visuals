import { pgTable, uuid, text, integer, jsonb, timestamp, index } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";

/* Book the Artist (#158) — performance bookings with escrow, on the
 * sponsors escrow pattern (lib/db/src/schema/sponsor-deals.ts).
 *
 * A promoter or venue books an artist for a live performance: show
 * date, venue facts, and a fee. The fee is held in ESCROW when the
 * promoter funds it and is released to the artist only after the show
 * is marked complete and the promoter releases it. The platform fee
 * (15%, PERFORMANCE_BOOKING_FEE_BPS — the sponsors escrow rate) comes
 * out of the fee at release; the promoter pays the agreed fee, nothing
 * extra.
 *
 * Booking lifecycle: proposed → accepted → funded → completed → paid
 *   (plus declined | cancelled)
 * Escrow lifecycle:  unfunded → funding → funded → released
 *   (a funded booking that is cancelled reads refunded once the refund
 *   rail has run — see routes/performance-bookings.ts)
 *
 * `terms` is the structured deal the two sides agreed to; `plainWords`
 * is the auto-generated plain-English summary of those terms,
 * regenerated by lib/performance-bookings.ts on every write that
 * changes them, so the record always carries words a human can read
 * without a lawyer. Money is REAL dollars via Stripe — never Visual
 * Bucs (the two economies are never mixed).
 *
 * Provisional migration: lib/db/migrations/0290_performance_bookings.sql
 * (renumbered at the stack join, like every lane migration). */

export interface PerformanceBookingTerms {
  /** What the artist is booked to do, e.g. "45-minute headline set". */
  performance: string;
  /** Set length in minutes, when agreed. */
  setLengthMin?: number | null;
  /** Who provides sound/lighting/backline, in the parties' own words. */
  productionNotes?: string | null;
  /** Cancellation terms in the parties' own words, when agreed. */
  cancellationTerms?: string | null;
}

export const performanceBookingsTable = pgTable("performance_bookings", {
  id:             uuid("id").primaryKey().defaultRandom(),
  /* The artist being booked: their creator profile + owning user. */
  profileId:      uuid("profile_id").notNull(),
  artistUserId:   text("artist_user_id").notNull(),
  artistName:     text("artist_name").notNull(),
  /* The promoter/venue side: the signed-in user placing the booking
   * and the name they book under (venue, company, or their own). */
  promoterUserId: text("promoter_user_id").notNull(),
  promoterName:   text("promoter_name").notNull(),
  /* The show. */
  eventTitle:     text("event_title").notNull(),
  eventDate:      timestamp("event_date", { withTimezone: true }).notNull(),
  venueName:      text("venue_name").notNull(),
  venueAddress:   text("venue_address").notNull(),
  venueCity:      text("venue_city").notNull(),
  /* The deal. feeCents is the full performance fee the promoter pays;
   * the platform fee and artist payout are only fixed at release. */
  feeCents:       integer("fee_cents").notNull(),
  terms:          jsonb("terms").$type<PerformanceBookingTerms>().notNull(),
  plainWords:     text("plain_words").notNull(),
  notes:          text("notes"),
  /* Lifecycle + escrow (sponsors pattern). */
  status:         text("status").notNull().default("proposed"),
  escrowStatus:   text("escrow_status").notNull().default("unfunded"),
  stripeSessionId:       text("stripe_session_id"),
  stripePaymentIntentId: text("stripe_payment_intent_id"),
  platformFeeCents:      integer("platform_fee_cents"),
  artistPayoutCents:     integer("artist_payout_cents"),
  paidAt:         timestamp("paid_at", { withTimezone: true }),
  createdAt:      timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt:      timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
}, (t) => [
  index("performance_bookings_artist_idx").on(t.artistUserId, t.status),
  index("performance_bookings_promoter_idx").on(t.promoterUserId, t.status),
  index("performance_bookings_profile_idx").on(t.profileId),
]);

export const insertPerformanceBookingSchema = createInsertSchema(performanceBookingsTable).omit({
  id: true, createdAt: true, updatedAt: true,
});
export type InsertPerformanceBooking = z.infer<typeof insertPerformanceBookingSchema>;
export type PerformanceBooking = typeof performanceBookingsTable.$inferSelect;
